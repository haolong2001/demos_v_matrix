def export_fertility_matrix_to_csv(fertility_matrix, output_path="fertility_matrix_sample.csv"):
    """
    Export a sample of the fertility matrix to CSV for inspection.
    This helps verify the data structure and values.
    """
    if fertility_matrix is None:
        print("No fertility matrix to export")
        return
    
    try:
        # Create a sample dataframe with key fertility rates
        sample_data = []
        years = [1980, 1990, 2000, 2010, 2020, 2030, 2040, 2050]
        ages = [15, 20, 25, 30, 35, 40, 45]
        ethnicities = ['chinese_male', 'chinese_female', 'malay_male', 'malay_female', 
                      'indian_male', 'indian_female', 'other_male', 'other_female']
        
        for year in years:
            year_idx = year - 1990
            if year_idx > fertility_matrix.shape[1]:  # Check bounds for years
                raise ValueError(f"Year {year} is out of bounds")
            for age in ages:
                age_idx = age - 15
                if age_idx > fertility_matrix.shape[2]:  # Check bounds for ages
                    raise ValueError(f"Age {age} is out of bounds")
                for eth_idx, ethnicity in enumerate(ethnicities):
                    if eth_idx % 2 == 1:  # Only females
                        # Access as [ethnicity][time][age]
                        print(f"eth_idx: {eth_idx}, year_idx: {year_idx}, age_idx: {age_idx}")
                        # Map ethnicity index to race_idx for mapping function
                        
                        race_idx = eth_idx
                        rate = map_fertility_rate(fertility_matrix, race_idx, year_idx, age)
                        sample_data.append({
                            'year': year,
                            'age': age,
                            'ethnicity': ethnicity,
                            'fertility_rate': rate
                        })
        
        sample_df = pd.DataFrame(sample_data)
        sample_df.to_csv(output_path, index=False)
        print(f"Fertility matrix sample exported to {output_path}")
        
        # Also show a summary table
        print("\nFertility Matrix Summary (sample values):")
        pivot_df = sample_df.pivot_table(
            values='fertility_rate', 
            index=['year', 'age'], 
            columns='ethnicity', 
            aggfunc='first'  # Use 'first' to handle any duplicate entries by taking the first occurrence
        )
        # Maintain the original order (Chinese, Malay, Indian, Other)
        desired_order = ['chinese_female', 'malay_female', 'indian_female', 'other_female']
        pivot_df = pivot_df.reindex(columns=desired_order)
        print(pivot_df.round(4))
        
    except Exception as e:
        print(f"Error exporting fertility matrix: {e}")

def test_fertility_mapping(fertility_matrix):
    """
    Test the fertility rate mapping logic to ensure it produces reasonable results.
    """
    if fertility_matrix is None:
        print("No fertility matrix to test")
        return
    
    print("\nTesting Fertility Rate Mapping Logic:")
    print("=" * 50)
    
    # Test cases based on the C++ logic
    test_cases = []
    years = range(1990, 2015)  # 2024-2030
    races = ['chinese', 'malay', 'indian', 'other']
    ages = range(15, 26)  # 15-25
    
    for year in years:
        for race in races:
            for age in ages:
                test_cases.append({
                    'year': year,
                    'age': age,
                    'race': race,
                    'expected_range': (0.0, 1.0)
                })
    
    race_to_idx = {'chinese': 1, 'malay': 3, 'indian': 5, 'other': 7}  # Female indices
    # These will be converted by map_fertility_rate: 1->0, 3->1, 5->2, 7->3
    
    for test_case in test_cases:
        year = test_case['year']
        age = test_case['age']
        race = test_case['race']
        expected_min, expected_max = test_case['expected_range']
        
        race_idx = race_to_idx.get(race, 0)
        year_idx = year - 1990
        rate = map_fertility_rate(fertility_matrix, race_idx, year_idx, age)
        
        # Check if rate is within expected range
        is_valid = expected_min <= rate <= expected_max
        
        status = "✓" if is_valid else "✗"
        print(f"{status} {race.capitalize()}, year {year}, age {age}: {rate:.6f}")
        
        if not is_valid:
            print(f"    Warning: Rate {rate:.6f} outside expected range [{expected_min}, {expected_max}]")
    
    print("\nFertility Rate Mapping Test Complete")

def generate_fertility_params() -> pd.DataFrame:
    """
    Generate fertility parameters by reading the AESFR_matrix_combine.bin file
    and applying the fertility logic from fertility.cpp.
    """
    # Try to read the binary file (relative to project root)
    binary_filepath = "../data/bin/AESFR_matrix_combine.bin"
    fertility_matrix = read_aesfr_binary_file(binary_filepath)
    
    # Print matrix information
    if fertility_matrix is not None:
        print_fertility_matrix(fertility_matrix)
        
        # Test the mapping logic
        test_fertility_mapping(fertility_matrix)
        
        # Export sample for inspection
        export_fertility_matrix_to_csv(fertility_matrix)
    
    # Create the base dataframe
    df = pd.DataFrame(
        itertools.product(SIM_YEARS, RACES, AGES),
        columns=['sim_year', 'agent_race', 'agent_age'],
    )
    
    if fertility_matrix is not None:
        # Use real fertility rates from the binary file
        print("Using fertility rates from AESFR_matrix_combine.bin")
        
        # Map race names to indices (assuming order matches the C++ code)
        # Based on the C++ code, the mapping seems to be:
        # 0: Chinese male, 1: Chinese female, 2: Malay male, 3: Malay female, etc.
        # We use female indices for fertility calculations
        # The map_fertility_rate function will convert these to matrix indices:
        # 1 (Chinese) -> 0, 3 (Malay) -> 1, 5 (Indian) -> 2, 7 (Other) -> 3
        race_to_idx = {'chinese': 1, 'malay': 3, 'indian': 5, 'other': 7}
        
        def get_fertility_rate(row):
            
            race_idx = race_to_idx.get(row['agent_race'], 0)

            year_idx = row['sim_year'] - 1990  # Convert to relative year index
            age = row['agent_age']
            
            return map_fertility_rate(fertility_matrix, race_idx, year_idx, age)
        
        df['birth_prob'] = df.apply(get_fertility_rate, axis=1)
        
        # Set fertility to 0 for ages outside childbearing range
        age_mask = (df['agent_age'] < CHILDBEARING_START_AGE) | (df['agent_age'] > CHILDBEARING_END_AGE)
        df.loc[age_mask, 'birth_prob'] = 0.0
        
        print(f"Fertility parameters generated successfully.")
        print(f"  Total rows: {len(df)}")
        print(f"  Non-zero birth probabilities: {np.count_nonzero(df['birth_prob'])}")
        print(f"  Birth probability range: {df['birth_prob'].min():.6f} - {df['birth_prob'].max():.6f}")
        
        # Show sample fertility rates for different ages and ethnicities
        sample_ages = [20, 25, 30, 35, 40]
        print(f"\nSample fertility rates for year {START_YEAR}:")
        for age in sample_ages:
            for race in RACES:
                rate = df[(df['sim_year'] == START_YEAR) & 
                         (df['agent_race'] == race) & 
                         (df['agent_age'] == age)]['birth_prob'].iloc[0]
                print(f"  {race.capitalize()}, age {age}: {rate:.6f}")
        
    else:
        # Fallback to default values if binary file not found
        print("Using default fertility rates (fallback)")
        df['birth_prob'] = 0.0
        age_in_range = (df['agent_age'] > 14) & (df['agent_age'] < 50)
        df.loc[age_in_range, 'birth_prob'] = 0.5
    
    return df


def generate_immigration_params() -> pd.DataFrame:
    df = pd.DataFrame(
        itertools.product(SIM_YEARS, GENDERS, RACES, AGES),
        columns=['sim_year', 'gender', 'race', 'migrant_age'],
    )
    df['migrant_count'] = 0
    df.loc[df['migrant_age'] == 30, 'migrant_count'] = 1
    return df


def generate_death_params() -> pd.DataFrame:
    df = pd.DataFrame(
        itertools.product(SIM_YEARS, GENDERS, AGES),
        columns=['sim_year', 'agent_gender', 'agent_age'],
    )
    df['agent_death_prob'] = 0.1
    return df


