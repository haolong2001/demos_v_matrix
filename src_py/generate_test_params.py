    # Compare specific ethnicities
    print("\nComparing Chinese female (1) vs Malay female (3):")
    chinese_female = fertility_matrix[1, 10:20, 10:30]
    malay_female = fertility_matrix[3, 10:20, 10:30]
    print(f"Chinese female values: {chinese_female}")
    print(f"Malay female values: {malay_female}")
    print(f"Are they identical? {np.array_equal(chinese_female, malay_female)}")
    
    # Check if the issue is with the binary file reading
    print("\nChecking first few values of each ethnicity:")
    print("Note: eth 0,1,2,3 corresponds to Chinese, Malay, Indian, Others (via map_fertility_rate function)")
    for eth in range(0, 4):
        first_values = fertility_matrix[eth, 0, 0:5]
        print(f"Ethnicity {eth} [0, 0:5]: {first_values}")
    
