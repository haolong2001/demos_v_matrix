#!/usr/bin/env python3
"""
Generate Test Parameters for Demographic Simulation

This script generates test parameters for immigration, fertility, and death rates.
The fertility parameters are now generated by reading the AESFR_matrix_combine.bin file,
which contains real fertility rate data from the C++ demographic simulation.

Key Features:
- Reads binary fertility data from AESFR_matrix_combine.bin
- Applies the same fertility logic as the C++ fertility.cpp implementation
- Generates realistic fertility parameters based on age, ethnicity, and year
- Includes validation and testing functions
- Exports sample data for inspection

File Structure:
- AESFR_matrix_combine.bin: Binary file with fertility rates [12][71][35]
  - 12 ethnicities (including gender variations)
  - 71 time periods (1980-2050)
  - 35 age groups (15-49 years)

Usage:
    python generate_test_params.py
    
    # Test fertility reading only:
    python test_fertility_reading.py

Dependencies:
    - pandas
    - numpy
    - struct (built-in)
    - os (built-in)

Author: Modified to integrate with C++ demographic simulation
"""

import itertools
import json
import struct
import numpy as np
import pandas as pd
import os

GENDERS = ['male', 'female']
RACES = ['chinese', 'malay', 'indian', 'other']

START_YEAR = 2024
END_YEAR = 2030
SIM_YEARS = np.arange(START_YEAR, 1 + END_YEAR)
AGES = np.arange(85 + 1)

# Constants from C++ code
FER_MAT_SIZE = 12 * 71 * 35  # 12 ethnicities, 71 time periods, 35 age groups
CHILDBEARING_START_AGE = 15
CHILDBEARING_END_AGE = 49

def read_aesfr_binary_file(filepath):
    """
    Read the AESFR_matrix_combine.bin file and return the fertility rates matrix.
    
    The file contains double precision data in format [12][71][35]:
    - 12 ethnicities (including gender variations)
    - 71 time periods (1980-2050)
    - 35 age groups (15-49)
    """
    if not os.path.exists(filepath):
        print(f"Warning: {filepath} not found. Using default fertility rates.")
        return None
    
    try:
        with open(filepath, 'rb') as file:
            # Read double precision data
            data = file.read(FER_MAT_SIZE * 8)  # 8 bytes per double
            if len(data) != FER_MAT_SIZE * 8:
                print(f"Warning: Expected {FER_MAT_SIZE * 8} bytes, got {len(data)}")
                return None
            
            # Convert to double array
            double_array = struct.unpack('d' * FER_MAT_SIZE, data)
            
            # Reshape to 3D array [12][71][35] (ethnicities, time periods, age groups)
            fertility_matrix = np.array(double_array).reshape(12, 71, 35)
            
            print(f"Successfully loaded fertility matrix: {fertility_matrix.shape}")
            
            # Debug: Check if different ethnicities have different data
            print("\nDebug: Checking data uniqueness across ethnicities:")
            for eth in range(0, 4):
                first_values = fertility_matrix[eth, 0, 0:5]
                print(f"Ethnicity {eth} first values: {first_values}")
            
            # Check if the issue might be with the reshape
            print(f"\nDebug: Raw array stats - min: {np.array(double_array).min():.6f}, max: {np.array(double_array).max():.6f}")
            
            return fertility_matrix
            
    except Exception as e:
        print(f"Error reading {filepath}: {e}")
        return None

def map_fertility_rate(fertility_matrix, ethnicity_idx, year_idx, age):
    """
    Map fertility rate from the matrix, following the C++ logic from fertility.cpp.
    
    Args:
        fertility_matrix: 3D array [12][71][35] (ethnicities, time periods, age groups)
        - 12 ethnicities (including gender variations)
        - 71 time periods (1980-2050) 
        - 35 age groups (15-49)
        ethnicity_idx: ethnicity index (1,3,5,7) where:
            - 1: Chinese female -> matrix_idx 0
            - 3: Malay female -> matrix_idx 1  
            - 5: Indian female -> matrix_idx 2
            - 7: Other female -> matrix_idx 3
        year_idx: year index relative to 1990
        age: age of the person
    
    Returns:
        fertility rate for the given parameters
    """
    if age < CHILDBEARING_START_AGE or age > CHILDBEARING_END_AGE:
        return 0.0
    
    # Convert ethnicity index to matrix index (similar to C++ index/2 logic)
    # This maps: 1->0 (Chinese), 3->1 (Malay), 5->2 (Indian), 7->3 (Other)
    matrix_idx = ethnicity_idx // 2 
    # Map year index (C++ logic: year_idx + 10)
    matrix_year_idx = year_idx + 10
    
    # Map age (C++ logic: age - 15)
    matrix_age_idx = age - CHILDBEARING_START_AGE
    
    
    # Bounds checking
    if (matrix_year_idx < 0 or matrix_year_idx >= 71 or 
        matrix_age_idx < 0 or matrix_age_idx >= 35 or
        matrix_idx >= 12):
        return 0.0
    
    # Access as [ethnicity][time][age] since matrix is [12][71][35]
    return float(fertility_matrix[matrix_idx, matrix_year_idx, matrix_age_idx])

